from typing import Any, Optional
from uuid import UUID
from pydantic import BaseModel, Field

class TokenUsage(BaseModel):
    """Schema for DeepSeek token usage details."""
    prompt_tokens: int = Field(..., description="Number of tokens in the prompt.")
    completion_tokens: int = Field(..., description="Number of tokens in the completion.")
    total_tokens: int = Field(..., description="Total count of tokens used (prompt + completion).")


class ChatResponse(BaseModel):
    """API Response Schema for successful message endpoint requests."""
    success: bool = Field(default=True, description="Indicates if the request was successfully processed.")
    conversation_id: UUID = Field(..., description="The UUID of the conversation session.")
    message: str = Field(..., description="The response text generated by the AI assistant.")
    usage: TokenUsage = Field(..., description="Token usage details for this specific request.")
    reasoning_details: Optional[Any] = Field(default=None, description="Optional reasoning details / chain-of-thought of the model.")
